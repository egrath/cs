#!/bin/sh
# buildno.sh HEADER COUNTFILE
# Bump the build counter (COUNTFILE) and write the generated header:
# the number counts SOURCE-CHANGING builds - the Makefile regenerates
# the header as a rule that depends on the source files, so a no-op
# make does not increment.  The counter file survives make clean.
n=$(cat "$2" 2>/dev/null)
case "$n" in
''|*[!0-9]*) n=0 ;;
esac
n=$((n + 1))
echo "$n" > "$2" || exit 1
printf '/* generated by tools/buildno.sh - do not edit */\n#define CS_BUILDNO %d\n' "$n" > "$1" || exit 1
