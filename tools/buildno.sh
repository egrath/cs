#!/bin/sh
# buildno.sh HEADER COUNTFILE
# Bump the build counter (COUNTFILE) and write the generated header:
# the number counts SOURCE-CHANGING builds - the Makefile regenerates
# the header as a rule that depends on the source files, so a no-op
# make does not increment.  The counter file survives make clean.
# PORTABLE ACROSS THE SHELLS (user, 2026-11-23): bourne, c-shell and
# bourne-again - NO $(...) command substitution (ULTRIX's Bourne sh
# lacks it), NO $(( )) arithmetic, NO printf; backticks, expr, test
# and echo are the Bourne core.
if test "$#" -ne 2; then
    echo "Usage: buildno.sh HEADER COUNTFILE" >&2
    exit 1
fi

n=`cat "$2" 2>/dev/null`

case "$n" in
    ''|*[!0-9]*) n=0 ;;
esac

n=`expr "$n" + 1` || exit 1

echo "$n" > "$2" || exit 1

{
    echo '/* generated by tools/buildno.sh - do not edit */'
    echo "#define CS_BUILDNO $n"
} > "$1" || exit 1
